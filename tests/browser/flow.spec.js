import {test,expect} from '@playwright/test';
test('availability → match → individual commitments → confirmed, and revoke',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/');
 await expect(page.locator('.date-detail')).toContainText('3 of 4 have time');
 await page.locator('.date-detail [data-action="availability"]').click();
 await expect(page.getByRole('dialog')).toContainText('YAY!');
 await expect(page.getByRole('dialog')).toContainText('4/4 available');
 await expect(page.getByRole('dialog')).toContainText('Saturday, October 24');
 await page.getByRole('button',{name:'Let’s make a plan'}).click();
 await expect(page.locator('.date-detail')).toContainText('0 of 4 committed');
 await page.getByRole('button',{name:'I’M IN ✓',exact:true}).click();
 await expect(page.locator('.date-detail')).toContainText('1 of 4 committed');
 await expect(page.locator('.commitment-person.committed')).toHaveCount(1);
 await page.locator('[data-action="simulate"][data-id="katrine"]').click();
 await expect(page.locator('.date-detail')).toContainText('2 of 4 committed');
 await page.locator('[data-action="simulate"][data-id="naja"]').click();
 await expect(page.locator('.date-detail')).toContainText('3 of 4 committed');
 await expect(page.locator('[data-action="simulate"][data-id="naja"]')).toBeDisabled();
 await page.locator('[data-action="simulate"][data-id="cille"]').click();
 await expect(page.getByRole('dialog')).toContainText('IT’S A DATE!');
 await expect(page.getByRole('dialog')).toContainText('Saturday, October 24 is officially happening.');
 await page.getByRole('button',{name:'Can’t wait!'}).click();
 await expect(page.locator('.date-detail')).toHaveClass(/confirmed/);
 await expect(page.locator('.commitment-person.committed')).toHaveCount(4);
 await page.reload();await expect(page.locator('.date-detail')).toHaveClass(/confirmed/);
 await page.locator('.date-detail [data-action="availability"]').click();
 await expect(page.locator('.date-detail')).toContainText('3 of 4 have time');
 await expect(page.locator('.commitment')).toHaveCount(0);
 await expect(page.locator('[data-action="simulate"][data-id="cille"]')).toBeDisabled();
 expect(errors).toEqual([]);
});
test('weekend browsing, filtering, partial counts and mobile layout',async({page},testInfo)=>{
 await page.goto('/');
 const names=await page.locator('.day-name').allTextContents();expect(new Set(names)).toEqual(new Set(['Thu','Fri','Sat','Sun']));
 await expect(page.locator('.day-indicator').filter({hasText:'1/4 free'}).first()).toBeVisible();
 await expect(page.locator('.day-indicator').filter({hasText:'2/4 free'}).first()).toBeVisible();
 await page.getByRole('button',{name:'Next month'}).click();await expect(page.locator('.calendar-toolbar')).toContainText('November');
 await page.getByRole('button',{name:'Previous month'}).click();await expect(page.locator('.calendar-toolbar')).toContainText('October');
 await page.locator('[data-action="matched"]').click();expect(await page.locator('.weekend-card').count()).toBeGreaterThan(0);
 await page.locator('[data-action="all"]').click();await expect(page.locator('.weekend-card')).toHaveCount(5);
 await page.locator('.day-select[data-key="2026-10-17"]').click();await expect(page.locator('.date-detail')).toContainText('1 of 4 committed');
 await expect(page.locator('.date-detail [data-action="commit"]')).toBeEnabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.locator('[data-action="reset"]').click();await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:`/tmp/sunday-${testInfo.project.name}.png`,fullPage:true});
});
